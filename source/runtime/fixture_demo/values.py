"""Create an explicit demo overlay without changing production Helm values."""
import json
import os
from pathlib import Path
import yaml


def prepare_demo_values(project, report, *, previous_report=None):
    """Seed once; unresolved fixtures remain visible and cannot launch a server."""
    project = Path(project)
    path = project/'demo-values.yaml'
    infrastructure = dict(enabled=False, status=report['status'], issues=report['issues'])
    overlay = dict(image=dict(repository='', digest=''), demoInfrastructure=infrastructure)
    if report['status'] == 'prepared':
        binding = json.loads((project/'standalone/operation.json').read_text(encoding='utf-8'))['demo']
        root = (project/'standalone'/binding['tool_root']).resolve()
        from runtime.fixture_jdbc_tools.releases import file_hash
        from runtime.service_generation.deployment_configuration import service_name
        channel, operation = report['operation'].split('/',1)
        overlay['operation'] = dict(database='demo')
        overlay['databases'] = dict(demo=dict(jdbcUrl=binding['jdbc_url'], driverClass=binding['driver_class'],
            credentialsSecret=dict(name=service_name(channel,operation)+'-demo-database',usernameKey='username',passwordKey='password'),
            pool=dict(minimumIdle=0,maximumPoolSize=10,connectionTimeoutMs=30000,maxLifetimeMs=1800000)))
        overlay['image']['jdbcDriver'] = dict(path=os.path.relpath(root/binding['driver_jar'],project).replace('\\','/'),
            sha256=file_hash(root/binding['driver_jar']),driverClass=binding['driver_class'])
        infrastructure.update(bundleId=binding['bundle_id'],manifestHash=binding['manifest_hash'],
            toolRoot=os.path.relpath(root,project).replace('\\','/'),catalogue=os.path.relpath(report['catalogue'],project).replace('\\','/'),
            catalogueHash=report['catalogue_hash'],port=int(binding['jdbc_url'].split(':')[3].split('/')[0]),
            repository='',digest='',fixtureClaim='',fixtureMount='/fixtures',catalogueInContainer='',
            fixtureRoots=[],assetRootMap={})
    prefix=('# Explicit demo overlay. Production values.yaml remains unchanged.\n'
        '# Configure image digests and a read-only fixture PVC before enabling the sidecar.\n'
        )
    legacy=None
    if previous_report and previous_report.get('status')=='unavailable':
        old=dict(image=dict(repository='',digest=''),demoInfrastructure=dict(enabled=False,status='unavailable',issues=previous_report['issues']))
        # Older Windows outputs were written through text mode; accept only their exact generated bytes.
        legacy=prefix+yaml.safe_dump(old,sort_keys=False)
        if path.exists() and path.read_bytes()==legacy.replace('\n','\r\n').encode('utf-8'):
            legacy=legacy.replace('\n','\r\n')
    from runtime.fixture_demo.managed_outputs import write_demo_overlay
    if not write_demo_overlay(path,prefix+yaml.safe_dump(overlay,sort_keys=False),legacy_placeholder=legacy):
        report['overlay_notice']='Existing user-edited demo-values.yaml was preserved'
    return path
