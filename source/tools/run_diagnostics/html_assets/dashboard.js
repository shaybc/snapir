/* Offline navigation uses local scripts and DOM text nodes; saved model text is never HTML. */
(() => {
  'use strict';
  const data = window.diagnosticReport;
  const $ = id => document.getElementById(id);
  const node = (tag, text, className) => {
    const element = document.createElement(tag);
    if (text !== undefined) element.textContent = String(text);
    if (className) element.className = className;
    return element;
  };
  const badge = text => node('span', text, 'badge ' + String(text).replaceAll(' ', '-'));
  const pretty = value => JSON.stringify(value, null, 2);
  const details = (title, value) => {
    const element = node('details');
    element.append(node('summary', title), node('pre', typeof value === 'string' ? value : pretty(value)));
    return element;
  };
  const failures = new Map((data.analysis_failures || []).map(failure => [failure.id, failure]));
  $('analysis-failures').hidden = !failures.size;
  for (const failure of failures.values()) {
    $('analysis-failure-list').append(node('h3', failure.id), node('p', failure.message, 'notice'), details('Analysis failure evidence', failure));
  }
  const targetMap = new Map(data.targets.map(target => [target.identity, target]));
  const priority = ['failed', 'blocked', 'running or unknown', 'unknown', 'not started', 'validation recorded', 'completed', 'configuration bound', 'external policy'];
  const sorted = [...data.targets].sort((a, b) => priority.indexOf(a.status) - priority.indexOf(b.status) || a.name.localeCompare(b.name));
  let page = 0, evidenceLimit = 40, fileLimit = 60;
  let fileScope = null;
  const pageSize = 50;
  const link = (label, href) => {
    const anchor = node('a', label);
    // Only relative export paths generated by the exporter are accepted.
    if (typeof href === 'string' && !/^(?:[a-z][a-z0-9+.-]*:|\/|\\)/i.test(href) && !href.split('/').includes('..')) anchor.href = href;
    return anchor;
  };
  const materialLinks = materials => {
    const block = node('div', undefined, 'relations');
    for (const [name, reference] of Object.entries(materials || {})) {
      if (reference.href) block.append(link('Open ' + name, reference.href));
      else block.append(node('span', name + ': ' + (reference.export_error || 'not recorded')));
    }
    if (!block.childNodes.length) block.append(node('p', 'Materials not recorded.'));
    return block;
  };
  const relation = identity => {
    const target = targetMap.get(identity);
    if (!target) return node('span', identity + ' (not recorded)');
    const button = node('button', target.name + ' · ' + target.status, 'link-button');
    button.onclick = () => { location.hash = 'target=' + encodeURIComponent(identity); };
    return button;
  };
  function renderList() {
    const query = $('search').value.toLowerCase();
    const status = $('status').value, type = $('type').value, operation = $('operation').value, direction = $('direction').value;
    const filtered = sorted.filter(target =>
      (status === 'all' || (status === 'attention' ? ['failed', 'blocked'].includes(target.status) : status === target.status)) &&
      (type === 'all' || type === target.type) && (operation === 'all' || target.consumers.includes(operation)) &&
      (direction === 'all' || target.directions.includes(direction)) &&
      [target.name, target.identity, target.summary, ...target.consumers].join(' ').toLowerCase().includes(query));
    page = Math.min(page, Math.max(0, Math.ceil(filtered.length / pageSize) - 1));
    $('targets').replaceChildren();
    for (const target of filtered.slice(page * pageSize, (page + 1) * pageSize)) {
      const row = node('tr'), identity = node('td'), state = node('td');
      const button = node('button', target.name, 'link-button');
      button.onclick = () => { location.hash = 'target=' + encodeURIComponent(target.identity); };
      identity.append(button, node('div', target.type + (target.directions.length ? ' · ' + target.directions.join(', ') : ''), 'muted'));
      state.append(badge(target.status));
      const deliveries = target.attempts.reduce((count, attempt) => count + attempt.deliveries.length, 0);
      row.append(identity, state, node('td', target.attempts.length + ' / ' + (deliveries || 'not recorded')), node('td', target.summary));
      $('targets').append(row);
    }
    $('result-count').textContent = filtered.length + ' of ' + data.targets.length + ' components';
    $('empty').textContent = filtered.length ? '' : 'No components match. Choose All statuses to see successes, policy exclusions, or planned work.';
    $('page').textContent = filtered.length ? 'Page ' + (page + 1) + ' of ' + Math.ceil(filtered.length / pageSize) : '';
    $('previous').disabled = page === 0;
    $('next').disabled = (page + 1) * pageSize >= filtered.length;
  }
  function showDetail() {
    let identity;
    try { identity = location.hash.startsWith('#target=') ? decodeURIComponent(location.hash.slice(8)) : null; }
    catch { identity = null; }
    const target = targetMap.get(identity);
    $('detail').hidden = !target;
    $('conversion-section').hidden = !data.conversion || Boolean(target);
    if (!target) return;
    $('detail-title').textContent = target.name;
    const body = $('detail-body');
    body.replaceChildren();
    body.append(badge(target.status), node('p', target.summary, 'notice'));
    if (target.root_cause_ids?.length) {
      body.append(node('h3', target.failure_role === 'dependency_consequence' ? 'Dependency consequence' : 'Analysis consequence'));
      for (const id of target.root_cause_ids) {
        const failure = failures.get(id);
        body.append(node('p', id + ': ' + (failure?.message || 'Underlying failure details not recorded.')));
      }
      const causes = node('button', 'Show underlying analysis failures');
      causes.onclick = () => $('analysis-failures').scrollIntoView();
      body.append(causes);
    }
    const facts = node('dl');
    for (const [key, value] of Object.entries({Identity: target.identity, Type: target.type, Direction: target.directions.join(', ') || 'Not recorded', Result: target.result, 'Consuming operations': target.consumers.join(', ') || 'Not recorded'})) {
      facts.append(node('dt', key), node('dd', value));
    }
    body.append(facts);
    const showFiles = node('button', 'Show this component’s files');
    showFiles.onclick = () => {
      fileScope = target; fileLimit = 60; $('file-search').value = ''; renderFiles(); $('files').scrollIntoView();
    };
    body.append(showFiles);
    for (const [title, values] of [['Prerequisites', target.prerequisites], ['Dependent components', target.dependents]]) {
      body.append(node('h3', title));
      const block = node('div', undefined, 'relations');
      for (const id of values || []) block.append(relation(id));
      if (!block.childNodes.length) block.append(node('span', 'None recorded.'));
      body.append(block);
    }
    body.append(node('h3', 'Budget checks · checks are not transmissions'));
    for (const check of target.budget_checks) {
      const block = details((check.timestamp || 'Time not recorded') + ' · ' + check.decision + ' · ' + (check.characters ?? '?') + ' / ' + (check.character_limit ?? '?') + ' characters', {stage: check.stage, decision: check.decision});
      block.append(materialLinks(check.materials)); body.append(block);
    }
    if (!target.budget_checks.length) body.append(node('p', 'Budget checks not recorded.'));
    body.append(node('h3', 'Conversion attempts'));
    for (const attempt of target.attempts) {
      const block = node('details');
      block.append(node('summary', 'Attempt ' + (attempt.number ?? '?') + ' · ' + attempt.category + ' · ' + attempt.outcome.replaceAll('_', ' ')));
      block.append(node('p', attempt.timestamp || 'Timestamp not recorded.', 'muted'));
      if (attempt.error_summary) block.append(node('pre', attempt.error_summary));
      if (attempt.parser_location) block.append(node('p', 'JSON error location: ' + pretty(attempt.parser_location)));
      block.append(materialLinks(attempt.materials));
      block.append(node('h3', 'Delivery attempts'));
      for (const delivery of attempt.deliveries) {
        block.append(node('p', 'Delivery ' + (delivery.number ?? '?') + ' · ' + delivery.outcome.replaceAll('_', ' ') + ' · HTTP ' + (delivery.http_status ?? 'not captured')));
        if (delivery.error_material) block.append(materialLinks({error: delivery.error_material}));
        if (delivery.events) block.append(details('Recorded delivery timeline', delivery.events));
      }
      if (!attempt.deliveries.length) block.append(node('p', 'Delivery count and HTTP status not recorded.'));
      block.append(details('Saved evidence references', attempt.evidence || []));
      body.append(block);
    }
    if (!target.attempts.length) body.append(node('p', 'No conversion attempt recorded. See budget checks and prerequisite failures.'));
    for (const key of ['source_entry_points', 'format_lifecycles', 'planned_components', 'result_evidence', 'legacy_delivery_evidence']) {
      if (target[key]) body.append(details(key.replaceAll('_', ' '), target[key]));
    }
    const matches = data.saved_evidence.filter(item => item.name === target.name || item.identity === target.identity || (target.members || []).includes(item.identity));
    if (matches.length) body.append(details('Saved indexing and analysis records', matches));
    body.append(node('p', 'A missing declaring class or method signature means it was not recorded. This dashboard does not reconstruct analyzer decisions.', 'muted'));
    $('detail').focus({preventScroll: true}); $('detail').scrollIntoView();
  }
  function renderEvidence() {
    const query = $('evidence-search').value.toLowerCase();
    const status = $('evidence-status').value;
    const rows = data.saved_evidence.filter(item => (status === 'all' || (status === 'attention' ?
      item.kind === 'saved boundary analysis' && (item.status !== 'identified' || item.details?.issues?.length) : item.status === status)) &&
      [item.name, item.identity, item.status].join(' ').toLowerCase().includes(query));
    $('evidence-list').replaceChildren();
    for (const item of rows.slice(0, evidenceLimit)) {
      const block = details(item.name + ' · ' + item.status + ' · ' + item.kind, item);
      block.className = 'evidence-row';
      if (item.href) block.append(link('Open saved report', item.href));
      const matches = data.targets.filter(target => target.name === item.name || (target.members || []).includes(item.identity));
      for (const target of matches) block.append(relation(target.identity));
      $('evidence-list').append(block);
    }
    $('evidence-count').textContent = rows.length + ' saved records; showing ' + Math.min(rows.length, evidenceLimit);
    $('more-evidence').hidden = rows.length <= evidenceLimit;
  }
  function renderFiles() {
    const query = $('file-search').value.toLowerCase();
    const folders = new Set();
    if (fileScope) {
      for (const attempt of [...fileScope.attempts, ...fileScope.budget_checks]) {
        const references = [...Object.values(attempt.materials || {}), ...attempt.deliveries?.map(delivery => delivery.error_material).filter(Boolean) || []];
        for (const reference of references) if (reference.exported_file) folders.add(reference.exported_file.slice(0, reference.exported_file.lastIndexOf('/') + 1));
      }
    }
    const files = data.files.filter(file => (!fileScope || [...folders].some(folder => file.path.startsWith(folder))) && file.path.toLowerCase().includes(query));
    $('file-scope').textContent = fileScope ? 'Files for ' + fileScope.name : '';
    $('all-files').hidden = !fileScope;
    $('file-list').replaceChildren();
    for (const file of files.slice(0, fileLimit)) {
      const row = node('div', undefined, 'file-row'); row.append(link(file.path, file.href)); $('file-list').append(row);
    }
    if (!files.length) $('file-list').append(node('p', 'No matching exported files in this snapshot.'));
    $('more-files').hidden = files.length <= fileLimit;
  }
  $('run-name').textContent = data.run_id;
  $('snapshot').textContent = 'Observed ' + new Date(data.observed_at).toLocaleString() + ' · Static snapshot; rerun the diagnostic to refresh.';
  $('run-state').append(badge(data.progress.status), node('span', '  ' + data.progress.checkpoint, 'muted'));
  $('progress-title').textContent = data.progress.scope;
  for (const stage of data.progress.stages) {
    const item = node('li', undefined, stage.current ? 'current' : '');
    item.append(node('strong', stage.marker + ' ' + stage.label), badge(stage.status)); $('stages').append(item);
  }
  for (const detail of data.progress.details) $('guidance').append(node('p', detail));
  $('guidance').append(node('p', 'Next step: ' + data.progress.next_step, 'notice'));
  for (const operation of data.progress.operations) $('operations').append(node('p', operation.operation_key + ' · ' + operation.status + ' · ' + operation.phase));
  const subsection = (rows, parent) => {
    for (const [, title, state, children] of rows) {
      const block = node('details'); block.append(node('summary', title + ' · ' + state)); subsection(children, block); parent.append(block);
    }
  };
  subsection(data.progress.subsections, $('subsections'));
  if (!data.progress.operations.length && !data.progress.subsections.length) $('operations').append(node('p', 'Detailed operation progress not recorded.'));
  for (const status of priority) {
    if (!data.counts[status]) continue;
    const option = node('option', status); option.value = status; $('status').append(option);
    const button = node('button'); button.append(node('b', data.counts[status]), node('span', status));
    button.onclick = () => { $('status').value = status; page = 0; renderList(); }; $('counts').append(button);
  }
  for (const [id, values] of [['type', data.targets.map(target => target.type)], ['operation', data.targets.flatMap(target => target.consumers)]]) {
    for (const value of [...new Set(values)].sort()) { const option = node('option', value); option.value = value; $(id).append(option); }
  }
  for (const id of ['search', 'status', 'type', 'operation', 'direction']) $(id).addEventListener('input', () => { page = 0; renderList(); });
  $('previous').onclick = () => { page--; renderList(); };
  $('next').onclick = () => { page++; renderList(); };
  $('back').onclick = () => { location.hash = ''; };
  window.addEventListener('hashchange', showDetail);
  $('saved-panel').addEventListener('toggle', () => { if ($('saved-panel').open) renderEvidence(); });
  $('evidence-search').oninput = () => { evidenceLimit = 40; renderEvidence(); };
  $('evidence-status').oninput = () => { evidenceLimit = 40; renderEvidence(); };
  $('more-evidence').onclick = () => { evidenceLimit += 40; renderEvidence(); };
  $('file-search').oninput = () => { fileLimit = 60; renderFiles(); };
  $('more-files').onclick = () => { fileLimit += 60; renderFiles(); };
  $('all-files').onclick = () => { fileScope = null; fileLimit = 60; renderFiles(); };
  $('folder-path').value = data.folder;
  if (data.folder_url.startsWith('file:')) $('folder-link').href = data.folder_url;
  $('copy-folder').onclick = async () => {
    try { await navigator.clipboard.writeText(data.folder); $('copy-folder').textContent = 'Copied'; }
    catch { $('folder-path').focus(); $('folder-path').select(); $('copy-folder').textContent = 'Path selected · press Ctrl+C'; }
  };
  for (const limitation of data.limitations) $('limitations').append(node('li', limitation));
  $('stage-diagnostic').hidden = data.conversion;
  $('diagnostic-text').textContent = data.diagnostic_lines.join('\n');
  renderList(); renderFiles(); showDetail();
})();
